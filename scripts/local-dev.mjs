// Developer tooling only: talks exclusively to the local Supabase instance.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { fileURLToPath } from "node:url";
import { parseEnv } from "node:util";
import { createClient } from "@supabase/supabase-js";
import { createServerClient, serializeCookieHeader } from "@supabase/ssr";

const root = fileURLToPath(new URL("../", import.meta.url));
const mode = process.argv[2];
if (mode !== "setup" && mode !== "login") {
  throw new Error("Usage: node scripts/local-dev.mjs setup|login");
}

const status = JSON.parse(
  execFileSync("supabase", ["status", "--output", "json"], {
    cwd: root,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "pipe"],
  }),
);
const apiUrl = status.API_URL;
const anonKey = status.ANON_KEY ?? status.PUBLISHABLE_KEY;
// Never use a hosted backend, even if the shell or .env.local points to one.
if (apiUrl !== "http://127.0.0.1:54321" || !anonKey) {
  throw new Error("Expected the local Supabase API at http://127.0.0.1:54321.");
}
const envPath = `${root}.env.local`;
if (existsSync(envPath)) {
  const env = parseEnv(readFileSync(envPath, "utf8"));
  if (
    env.NEXT_PUBLIC_SUPABASE_URL !== apiUrl ||
    env.NEXT_PUBLIC_SUPABASE_ANON_KEY !== anonKey
  ) {
    throw new Error(
      "Existing .env.local differs from local Supabase; refusing to overwrite it.",
    );
  }
} else if (mode === "setup") {
  writeFileSync(
    envPath,
    `# Local development only; generated by pnpm dev:setup.\nNEXT_PUBLIC_SUPABASE_URL=${apiUrl}\nNEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}\n`,
    { flag: "wx", mode: 0o600 },
  );
} else {
  throw new Error("Run pnpm dev:setup first.");
}

